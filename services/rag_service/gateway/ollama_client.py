"""Async HTTPX Client for Local Ollama Model Runtime.

Configured with keep_alive: -1 to retain Gemma/MedGemma model weights in GPU VRAM
and eliminate cold-start reload latency during medical emergencies.
"""

import json
import re
from typing import Any, Dict, Optional
import httpx


class OllamaClient:
    """Asynchronous client communicating with local Ollama runtime on port 11434."""

    def __init__(
        self,
        base_url: str = "http://127.0.0.1:11434",
        default_model: str = "medgemma:latest",
        timeout_seconds: float = 90.0
    ):
        self.base_url = base_url.rstrip("/")
        self.default_model = default_model
        self.timeout = timeout_seconds

    async def is_reachable(self) -> bool:
        """Check if local Ollama daemon is reachable and responding."""
        try:
            async with httpx.AsyncClient(timeout=3.0) as client:
                res = await client.get(f"{self.base_url}/api/tags")
                return res.status_code == 200
        except Exception:
            return False

    async def generate_json(
        self,
        prompt: str,
        model: Optional[str] = None,
        system_instruction: Optional[str] = None
    ) -> Dict[str, Any]:
        """Generate structured JSON response using local Ollama model.

        Parameters:
        ----------
        prompt: str
            Input prompt containing clinical context and instructions.
        model: Optional[str]
            Model name, defaults to medgemma:latest.
        system_instruction: Optional[str]
            System prompt enforcing medical grounding.

        Returns:
        -------
        Dict[str, Any]:
            Parsed JSON object generated by the model.
        """
        target_model = model or self.default_model
        endpoint = f"{self.base_url}/api/generate"

        payload = {
            "model": target_model,
            "prompt": prompt,
            "format": "json",
            "stream": False,
            "keep_alive": -1,  # Retain in GPU memory indefinitely
            "options": {
                "temperature": 0.1,
                "top_p": 0.9,
                "num_ctx": 8192,
                "num_predict": 1024
            }
        }
        if system_instruction:
            payload["system"] = system_instruction

        async with httpx.AsyncClient(timeout=self.timeout) as client:
            resp = await client.post(endpoint, json=payload)
            resp.raise_for_status()
            data = resp.json()
            raw_response_text = data.get("response", "{}").strip()
            if raw_response_text.startswith("```"):
                raw_response_text = re.sub(r"^```(?:json)?\s*", "", raw_response_text, flags=re.IGNORECASE)
                raw_response_text = re.sub(r"\s*```$", "", raw_response_text)
            try:
                return json.loads(raw_response_text)
            except json.JSONDecodeError:
                match = re.search(r"\{.*\}", raw_response_text, flags=re.DOTALL)
                if match:
                    return json.loads(match.group(0))
                raise
